package mihon.source.magazines

/**
 * A magazine (or magazine-style site) that publishes an open RSS/Atom feed.
 *
 * @param slug stable id, used in the entry's URL; never change it once shipped or library entries break
 * @param feed the publication's feed; entries are rebuilt from it on every refresh
 * @param fullTextInFeed true when the feed carries whole articles, so article pages needn't be fetched
 * @param color masthead background for the generated cover, as 0xRRGGBB
 * @param kind what [feed] points at: an RSS/Atom feed, or a substitute for sites that have none
 * @param issues how stories are bundled into issues (one chapter each), sized to how often the site publishes
 */
data class Publication(
    val slug: String,
    val name: String,
    val homepage: String,
    val feed: String,
    val tagline: String,
    val color: Int,
    val fullTextInFeed: Boolean = false,
    val kind: FeedKind = FeedKind.RSS,
    val archive: Archive? = null,
    val issues: IssuePeriod = IssuePeriod.MONTH,
)

/** Where a publication's older stories can be found, beyond what its feed lists. */
sealed interface Archive {
    /** The feed itself pages back: `feed?paged=2`, `feed?paged=3`… (WordPress and similar). */
    data object FeedPages : Archive

    /**
     * One sitemap per month, e.g. `https://www.gq.com/sitemap-{yyyy}-{MM}.xml`.
     *
     * @param pathFilter only addresses containing this belong to the publication (for a section of a site)
     */
    data class MonthlySitemap(val pattern: String, val pathFilter: String? = null) : Archive {
        fun url(year: Int, month: Int) = pattern
            .replace("{yyyy}", year.toString())
            .replace("{MM}", month.toString().padStart(2, '0'))
    }

    /** Numbered listing pages for a [FeedKind.NEXT_DATA] publication, e.g. `…/car-news/page/{n}`. */
    data class ListingPages(val pattern: String) : Archive {
        fun url(page: Int) = pattern.replace("{n}", page.toString())
    }

    /** The publication's [FeedKind.SITEMAP] already lists its whole history. */
    data object FullSitemap : Archive
}

/** Where a publication's list of stories comes from. */
enum class FeedKind {
    /** An RSS or Atom feed. */
    RSS,

    /** A sitemap listing the site's articles; titles are read from the articles themselves. */
    SITEMAP,

    /** A Next.js page whose embedded data lists the latest stories. */
    NEXT_DATA,
}

